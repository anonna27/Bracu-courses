"""**Preprocessing**"""

#checking if rows needs to be dropped
dataset['null_count'] = dataset.isnull().sum(axis=1)  # Count nulls per row
rows_with_most_nulls = dataset.sort_values(by='null_count', ascending=False)   # Sorting rows in descending order
rows_with_most_nulls.head(5)

#Since there are a lot of rows with more than 3 null values each we have to fill the null values
dataset.drop('null_count', axis=1, inplace=True)

#to fill up Categorical columns
categorical_cols = ['Location', 'Has_Balcony', 'Parking_Available', 'Nearby_Schools', 'Security_Level', 'Price_Category']
for col in categorical_cols:
    dataset[col].fillna(dataset[col].mode()[0], inplace=True)

#CHECKING
dataset.head(5)

# Checking skewness of all numerical columns
skew_values = dataset.select_dtypes(include=['float64', 'int64']).skew()
print("Skewness of Numerical Features:\n")
print(skew_values.sort_values(ascending=False))

#As all the numerical features are approximately symmetric(skewness close to 0)
#so we are using mean imputation
numerical_cols = ['Distance_to_CityCenter_km', 'Building_Age_Years', 'Num_Bathrooms',
                  'Size_sqft', 'Num_Bedrooms', 'Floor_Number']

for col in numerical_cols:
    dataset[col].fillna(dataset[col].mean(), inplace=True)
# Round only float columns to 2 decimals
float_cols = dataset.select_dtypes(include='float64').columns
dataset[float_cols] = dataset[float_cols].round(2)

print("\nMissing values per column:\n")
dataset.isnull().sum()

dataset.head(10)

#Encoding categorical variables
dataset['Location'] = dataset['Location'].map({'Countryside': 0, 'City Center': 1, 'Suburbs':2 })
dataset['Has_Balcony'] = dataset['Has_Balcony'].map({'Yes': 1, 'No': 0})
dataset['Parking_Available'] = dataset['Parking_Available'].map({'Yes': 1, 'No': 0})
dataset['Nearby_Schools'] = dataset['Nearby_Schools'].map({'Many': 1, 'Few': 0})
dataset['Security_Level'] = dataset['Security_Level'].map({'Low': 0, 'Medium': 1, 'High':2})
dataset['Price_Category'] = dataset['Price_Category'].map({'Low':0, 'Medium': 1, 'High':2})

dataset.head(11)

import seaborn as sns
corr_matrix = dataset.corr()

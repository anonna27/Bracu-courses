"""Dataset **splitting**"""

from sklearn.model_selection import train_test_split
# Separate features and target
X = dataset.drop('Price_Category', axis=1)
y = dataset['Price_Category']

# Stratified split
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, stratify=y, random_state=42)

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
# Fit on train data and transform both train and test
X_test_scaled = scaler.transform(X_test)

"""**Training** **Models**"""

# models
from sklearn.linear_model import LogisticRegression
from sklearn.naive_bayes import GaussianNB
from sklearn.neighbors import KNeighborsClassifier

# Logistic Regression
log_model = LogisticRegression()
log_model.fit(X_train_scaled, y_train)

# Naive Bayes
nb_model = GaussianNB()
nb_model.fit(X_train_scaled, y_train)

#KNN
knn_model = KNeighborsClassifier(n_neighbors=5)
knn_model.fit(X_train_scaled, y_train)

from sklearn.neural_network import MLPClassifier
# Creating a model with 1 hidden layer of 100 neurons
mlp_model = MLPClassifier(hidden_layer_sizes=(100,), max_iter=500, random_state=42)
mlp_model.fit(X_train_scaled, y_train)

"""**Predictions**"""

# Predictions of each model
y_pred_log = log_model.predict(X_test_scaled)
y_pred_nb = nb_model.predict(X_test_scaled)
y_pred_knn = knn_model.predict(X_test_scaled)
y_pred_mlp = mlp_model.predict(X_test_scaled)

"""**Probabilities**"""

# Probabilities of each model
y_prob_log = log_model.predict_proba(X_test_scaled)
y_prob_nb = nb_model.predict_proba(X_test_scaled)
y_prob_knn = knn_model.predict_proba(X_test_scaled)
y_prob_mlp = mlp_model.predict_proba(X_test_scaled)

# Import metrics
from sklearn.metrics import confusion_matrix, classification_report, precision_score, recall_score, f1_score, roc_auc_score, roc_curve, accuracy_score
import matplotlib.pyplot as plt

# Evaluation function
def evaluate_model(y_true, y_pred, y_prob, model_name):  #predict
    print(f"\nEvaluation for {model_name}")
    print("-" * 40)
    print("Confusion Matrix:\n", confusion_matrix(y_true, y_pred))
    print("\nClassification Report:\n", classification_report(y_true, y_pred))
    # Use 'weighted' average for precision, recall, and F1-score in multiclass problems
    print(f"Accuracy: {accuracy_score(y_true, y_pred):.4f}")
    print(f"Precision: {precision_score(y_true, y_pred, average='weighted'):.4f}")
    print(f"Recall: {recall_score(y_true, y_pred, average='weighted'):.4f}")
    print(f"F1 Score: {f1_score(y_true, y_pred, average='weighted'):.4f}")
    print(f"AUC Score: {roc_auc_score(y_true, y_prob, average='weighted', multi_class='ovr'):.4f}")

# Evaluate Logistic Regression
evaluate_model(y_test, y_pred_log, y_prob_log, "Logistic Regression")

# Evaluate Naive Bayes
evaluate_model(y_test, y_pred_nb, y_prob_nb, "Naive Bayes")

# Evaluate KNN
evaluate_model(y_test, y_pred_knn, y_prob_knn, "KNN")

#Evaluate MLP
evaluate_model(y_test, y_pred_mlp, y_prob_mlp, "Neural Network (MLP)")


import math
import random
def alpha_beta_search(depth, is_attacker, alpha, beta, max_value, min_value):
    if depth == 5:
        return calculate_utility_func(max_value, min_value)
    if is_attacker:
        best_score = -math.inf
        for move in range(2):
            score = alpha_beta_search(depth + 1, False, alpha,beta,max_value,min_value)
            best_score = max(best_score, score)
            alpha = max(alpha, best_score)
            if beta<=alpha:  # Prune
                break
        return best_score
    else:
        best_score = math.inf
        for move in range(2):
            score = alpha_beta_search(depth+1,True, alpha, beta, max_value,min_value)
            best_score = min(best_score, score)
            beta = min(beta, best_score)  # Update beta
            if beta<=alpha:  # Prune
                break
        return best_score


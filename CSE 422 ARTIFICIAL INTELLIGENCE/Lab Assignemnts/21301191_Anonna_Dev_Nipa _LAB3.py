def simple_minimax(depth, isMaxTurn, max_value,min_value):
    if depth == 5:
        return calculate_utility_func(max_value,min_value)
    if isMaxTurn:
        best_value = -float('inf')
        for i in range(2):  # 2 ta possible moves
            move_value = simple_minimax(depth + 1, False,max_value,min_value)
            best_value = max(best_value, move_value)
        return best_value
    else:
        best_value = float('inf')
        for i in range(2):
            move_value = simple_minimax(depth + 1, True, max_value,min_value)
            best_value = min(best_value, move_value)
        return best_value

